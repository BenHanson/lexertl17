struct test_case
{
    struct state
    {
        struct transition
        {
            std::uint16_t _next{0xffff};
            bool _negated{false};
            const char *_charset{nullptr};
            std::size_t _len{0};

            transition &operator=(const transition &rhs_)
            {
                if(&rhs_ != this)
                {
                    _next = rhs_._next;
                    _charset = rhs_._charset;
                }

                return *this;
            }
        };

        using transition_vector = std::vector<transition>;

        bool _end_state{false};
        std::uint16_t _id{0};
        std::uint16_t _next_dfa{0};
        std::uint16_t _eol_index{0xffff};
        transition_vector _transitions;
    };

    using state_vector = std::vector<state>;

    const char *_regex{nullptr};
    std::uint16_t _bol_index{0xffff};
    state_vector _states;

    test_case &operator=(const test_case &rhs_)
    {
        if(&rhs_ != this)
        {
            _regex = rhs_._regex;
            _bol_index = rhs_._bol_index;
            _states = rhs_._states;
        }

        return *this;
    }
};

