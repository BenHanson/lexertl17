bool success_tests()
{
    const std::size_t tests_ = test_cases_.size();
    test_case *test_case_ = &test_cases_.front();

    try
    {
        lexertl::rules rules_;
        lexertl::char_state_machine sm_;

        for (std::size_t i_ = 0; i_ < tests_; ++i_)
        {
            rules_.flags(*lexertl::regex_flags::dot_not_newline |
                *lexertl::regex_flags::match_zero_len);
            rules_.push(test_case_->_regex, 1);
            lexertl::char_generator::build(rules_, sm_);
            sm_.minimise();

            if (sm_._sm_vector.front()._bol_index != test_case_->_bol_index)
            {
                std::cout << "BOL mismatch: " <<
                    test_case_->_regex << '\n';
                return false;
            }

            for (const auto& dfa_ : sm_._sm_vector)
            {
                const std::size_t states_ = dfa_._states.size();

                if (states_ != test_case_->_states.size())
                {
                    std::cout << "Mismatch with number of states: " <<
                        test_case_->_regex << '\n';
                    return false;
                }

                auto iter_ = dfa_._states.begin();
                test_case::state *state_rhs_ = &test_case_->_states.front();

                for (std::size_t idx_ = 0, states_ = test_case_->_states.size();
                    idx_ < states_; ++idx_, ++iter_, ++state_rhs_)
                {
                    if (iter_->_end_state != state_rhs_->_end_state)
                    {
                        std::cout << "end state mismatch: " <<
                            test_case_->_regex << '\n';
                        return false;
                    }
                    else if (iter_->_id != state_rhs_->_id)
                    {
                        std::cout << "id mismatch: " <<
                            test_case_->_regex << '\n';
                        return false;
                    }
                    else if (iter_->_next_dfa != state_rhs_->_next_dfa)
                    {
                        std::cout << "dfa state mismatch for regex: " <<
                            test_case_->_regex << '\n';
                        return false;
                    }
                    else if (iter_->_eol_index != state_rhs_->_eol_index)
                    {
                        std::cout << "eol mismatch: " <<
                            test_case_->_regex << '\n';
                        return false;
                    }

                    const std::size_t transitions_ = iter_->_transitions.size();

                    if (transitions_ != state_rhs_->_transitions.size())
                    {
                        std::cout << "transition size mismatch: " <<
                            test_case_->_regex << '\n';
                        return false;
                    }

                    for (const auto& tran_ : state_rhs_->_transitions)
                    {
                        auto tran_iter_ = iter_->_transitions.find(tran_._next);

                        if (tran_iter_ == iter_->_transitions.end())
                        {
                            std::cout << "transition not found: " <<
                                test_case_->_regex << '\n';
                        }

                        std::string source_;
                        std::string dest_;

                        if (tran_._negated)
                        {
                            const char* ptr_ = tran_._charset;
                            std::size_t len_ = tran_._len;

                            for (int c_ = 0; c_ < 256; ++c_)
                            {
                                if (len_ && c_ == *ptr_)
                                {
                                    --len_;
                                    ++ptr_;
                                }
                                else
                                    source_ += c_ & 0xff;
                            }
                        }
                        else
                        {
                            source_.assign(tran_._charset,
                                tran_._charset + tran_._len);
                        }

                        for (const auto& pair_ : tran_iter_->second._ranges)
                        {
                            for (int c_ = pair_.first; c_ <= pair_.second; ++c_)
                                dest_ += c_ & 0xff;
                        }

                        if (source_ != dest_)
                        {
                            std::cout << "charset mismatch: " <<
                                test_case_->_regex << '\n';
                            return false;
                        }
                    }
                }
            }

            rules_.clear();
            sm_.clear();
            ++test_case_;
        }
    }
    catch(const std::exception &e)
    {
        std::cout << e.what();
        return false;
    }

    return true;
}

int main()
{
    init();

    if (success_tests())
    {
        std::cout << "All regex tests passed\n";
        return 0;
    }
    else
        return 1;
}
